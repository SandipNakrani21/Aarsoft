import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';

// Projections come from the authoritative content; regenerate before dev/build.
function data(name) {
  const source = fs.readFileSync(`data/${name}.ts`, 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
  const exports = {};
  vm.runInNewContext(compiled, { exports, require: id => {
    if (id === 'lucide-react') return new Proxy({}, { get: (_, key) => String(key) });
    throw new Error(`Unexpected content dependency ${id}`);
  } });
  return exports;
}
const { services } = data('services');
const { solutions } = data('solutions');
const { industries } = data('company');
const slug = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const mainNav = [
  { label: 'Services', href: '/services', menu: { intro: 'Engineering, design and cloud capabilities, from first idea to production.', items: services.map(s => ({ label: s.title, href: `/services/${s.slug}`, description: s.excerpt, icon: s.icon })) } },
  { label: 'Solutions', href: '/solutions', menu: { intro: 'Platforms built around a business outcome, not a technology.', items: solutions.map(s => ({ label: s.title, href: `/solutions#solution-${slug(s.title)}`, description: s.outcomes.slice(0,2).join(' · '), icon: s.icon })) } },
  { label: 'Industries', href: '/industries', menu: { intro: 'Sector knowledge that shapes the data model, compliance and rollout.', items: industries.map(i => ({ label: i.name, href: `/industries#industry-${slug(i.name)}`, description: i.description, icon: i.icon })) } },
  ...['About','Work','Insights'].map(label => ({ label, href: '/' + label.toLowerCase() })),
];
fs.writeFileSync('data/navigation.ts', `// Generated by scripts/generate-content.mjs; edit source content instead.\nexport type NavItem = { label: string; href: string; description?: string };\nexport type NavLink = NavItem & { menu?: { intro: string; items: (NavItem & { icon: string })[] } };\nexport const mainNav: NavLink[] = ${JSON.stringify(mainNav,null,2)};\n`);
fs.writeFileSync('data/service-options.ts', `// Generated lightweight form choices.\nexport const serviceNames = ${JSON.stringify(services.map(s=>s.title),null,2)};\n`);
const icons = [...new Set(mainNav.flatMap(n=>n.menu?.items.map(i=>i.icon) ?? []))];
fs.writeFileSync('components/ui/NavigationIcon.tsx', `// Generated presentation mapping; content contains plain icon keys.\nimport { ${icons.join(', ')} } from 'lucide-react';\nexport const navIcons = { ${icons.join(', ')} };\nexport function navigationIcon(key: string) { return navIcons[key as keyof typeof navIcons] ?? ${icons[0]}; }\n`);
